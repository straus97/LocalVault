    #[test]
    fn totp_status_is_generated_by_core_for_a_fixed_time() {
        let session = open_ok(schema2());
        let id = id_of(&session, "Fixture TOTP Account");

        let status = session
            .totp_status(id.clone(), TOTP_FIXED_UNIX_SECONDS)
            .unwrap();

        assert!(status.code == "27711647", "unexpected code");
        assert_eq!(status.period_seconds, 60);
        // 1_700_000_100 is exactly on a 60 s boundary.
        assert_eq!(status.remaining_seconds, 60);

        // Same period, later: same code, less time remaining.
        let later = session
            .totp_status(id.clone(), TOTP_FIXED_UNIX_SECONDS + 45)
            .unwrap();
        assert!(later.code == status.code, "code changed within a period");
        assert_eq!(later.remaining_seconds, 15);

        // Next period: the code rotates.
        let next = session
            .totp_status(id, TOTP_FIXED_UNIX_SECONDS + 60)
            .unwrap();
        assert!(next.code != status.code, "code did not rotate");
        assert_eq!(next.remaining_seconds, 60);
    }

